/// 需要单独的类别覆盖（首位数字推断不准确的科目）
fn category_override(code: &str) -> Option<AcctCategory> {
    match code {
        "6901" => Some(AcctCategory::Expense),
        "6101" | "6111" => Some(AcctCategory::Income),
        _ => None,
    }
}

/// 附加属性：辅助核算、外币、数量、现金/银行标记、现金流量项目
fn apply_extras(a: &mut Account) {
    let code = a.code.as_str();
    match code {
        "1001" => {
            a.is_cash = true;
            a.aux = AuxMask::NONE;
        }
        "1002" | "100201" | "100202" | "100203" | "100204" | "100205" | "100206" | "100207" => {
            a.is_bank = true;
            if code != "1002" {
                a.aux = AuxMask::NONE.with(AuxKind::Bank);
            }
        }
        "1122" | "112201" | "112202" | "2203" => a.aux = AuxMask::NONE.with(AuxKind::Customer),
        "1123" | "2202" | "220201" | "220202" => a.aux = AuxMask::NONE.with(AuxKind::Supplier),
        "1221" | "122101" | "122102" | "122103" | "122104" | "122105" => {
            a.aux = AuxMask::NONE.with(AuxKind::Employee)
        }
        "1403" | "1405" | "1411" | "1401" | "140301" | "140302" | "140303" | "140304"
        | "140305" | "140306" | "140501" | "140502" | "141101" | "141102" | "141103" => {
            a.aux = AuxMask::NONE.with(AuxKind::Item);
            a.has_qty = true;
            a.unit = Some("个".to_string());
        }
        "5001" | "5101" => a.aux = AuxMask::NONE.with(AuxKind::Dept),
        "6601" | "6602" | "6603" => a.aux = AuxMask::NONE.with(AuxKind::Dept),
        _ => {}
    }
    a.cash_flow_item = default_cash_flow_item(code);
}

/// 科目的默认现金流量项目（录入凭证时自动带出，用户可改）
fn default_cash_flow_item(code: &str) -> Option<String> {
    let c = match code {
        "1122" | "1121" | "2203" | "6001" | "6051" | "22210102" => "0101", // 销售收到的现金
        "2202" | "1123" | "2201" | "1403" | "1405" | "1411" | "6401" | "6402" => "0104", // 采购支付的现金
        "2211" | "221101" => "0105",                                     // 支付给职工
        "2221" | "222101" | "222102" | "222103" | "222104" | "222105" | "222106" | "6403" | "6801" => {
            "0106"
        } // 支付的税费
        "1601" | "1604" | "1701" | "1605" => "0204",                      // 购建长期资产
        "1511" | "1101" | "6111" => "0205",                               // 投资支付
        "2001" | "2501" => "0302",                                        // 取得借款
        "2231" | "2232" | "660301" | "660303" | "410403" => "0304",       // 偿付利息股利
        "4001" | "4002" => "0301",                                        // 吸收投资
        "6301" | "6711" | "6603" | "660101" | "660201" | "660304" => "0107",         // 其他经营
        _ => return None,
    };
    Some(c.to_string())
}

/// 默认科目表
///
/// 附加属性只保留在**末级科目**上：非末级科目不直接记账，挂辅助核算没有意义，
/// 也会干扰"按科目汇总"的口径（例如 1002 与 100201 同时标记银行科目会导致重复统计）。
pub fn default_accounts() -> Vec<Account> {
    let mut out = Vec::with_capacity(ACCOUNTS.len());
    for (code, name) in ACCOUNTS {
        let cat = category_override(code)
            .or_else(|| AcctCategory::from_code(code))
            .unwrap_or(AcctCategory::Asset);
        let mut a = Account::new(*code, *name, cat);
        apply_extras(&mut a);
        out.push(a);
    }

    let probe = Chart::with_accounts(CodeScheme::default(), out.clone());
    for a in out.iter_mut() {
        if !probe.is_leaf(&a.code) {
            a.aux = AuxMask::NONE;
            a.has_qty = false;
            a.unit = None;
            a.is_bank = false;
        }
    }
    out
}

/// 建好默认科目表的 `Chart`
pub fn default_chart() -> Chart {
    Chart::with_accounts(CodeScheme::default(), default_accounts())
}

