#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn codes_fit_scheme() {
        let s = CodeScheme::default();
        for (code, _) in ACCOUNTS {
            assert!(s.is_valid_code(code), "科目编码 {code} 不符合级长方案");
        }
    }

    #[test]
    fn parents_exist() {
        let c = default_chart();
        for (code, _) in ACCOUNTS {
            if let Some(p) = c.parent_code(code) {
                assert!(c.contains(&p), "科目 {code} 的上级 {p} 不存在");
            }
        }
    }

    #[test]
    fn no_duplicates() {
        let mut seen = std::collections::BTreeSet::new();
        for (code, _) in ACCOUNTS {
            assert!(seen.insert(*code), "重复科目编码 {code}");
        }
    }

    #[test]
    fn profit_accounts_present() {
        let c = default_chart();
        for need in ["4103", "410401", "600101", "1001", "100201", "660101"] {
            assert!(c.contains(need), "缺少关键科目 {need}");
            assert!(c.is_leaf(need), "{need} 应是末级科目");
        }
        // 有下级的科目不能直接记账
        for parent in ["1002", "6001", "6601", "6602", "6603", "4104", "5001"] {
            assert!(!c.is_leaf(parent), "{parent} 应为非末级科目");
        }
    }

    #[test]
    fn cash_bank_flags() {
        let c = default_chart();
        assert!(c.get("1001").unwrap().is_cash);
        assert!(c.get("100201").unwrap().is_bank);
        assert!(!c.get("1002").unwrap().is_bank); // 非末级不标记，避免重复统计
    }
}
